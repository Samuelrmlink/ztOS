#!/usr/bin/env python3
"""Write therm-tables.h from ../starlte-rev26.json (stock's decoding tables).

    python3 -I power/thermistors/zrn-therm/gen-tables.py > power/thermistors/zrn-therm/therm-tables.h
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, '..', 'starlte-rev26.json')))
# zrn-therm's channels, in its order: its name, the JSON's name
want = [('battery', 'battery'), ('usb', 'usb'), ('charger', 'charger'),
        ('ap', 'sec-ap-thermistor'), ('wifi', 'sec-wf-thermistor'), ('pa', 'sec-pa-thermistor')]
by = {t['name']: t for t in d['thermistors']}
out = ['/* SPDX-License-Identifier: GPL-2.0 */',
       '/* Generated by gen-tables.py from starlte-rev26.json (%s). Do not edit. */' % d['source'],
       '#ifndef THERM_TABLES_H', '#define THERM_TABLES_H', '#include "therm-decode.h"', '']
for name, src in want:
    t = by[src]
    adc, deci = t['adc'], t['deci_c']
    if any(b <= a for a, b in zip(adc, adc[1:])):
        sys.exit(f'gen-tables: {src} ADC points do not rise')
    out.append(f'static const int therm_{name}_adc[] = {{ {", ".join(map(str, adc))} }};')
    out.append(f'static const int therm_{name}_deci[] = {{ {", ".join(map(str, deci))} }};')
out.append('')
out.append('struct therm_channel { const char *name; int ch; struct therm_table t; };')
out.append('static const struct therm_channel therm_channels[] = {')
for name, src in want:
    out.append(f'\t{{ "{name}", {by[src]["adc_channel"]}, {{ therm_{name}_adc, therm_{name}_deci, '
               f'(int)(sizeof(therm_{name}_adc) / sizeof(int)) }} }},')
out.append('};')
out.append('#define THERM_N_CHANNELS (int)(sizeof(therm_channels) / sizeof(therm_channels[0]))')
out.append('#endif')
print('\n'.join(out))
