/* Host test of the stage-2 NCI allowlist: cc -o t test-nci-filter.c && ./t */
#include <stdio.h>
#include "nci-filter.h"

static int fails;

static void t(int want_ok, unsigned char proto, const char *name,
	      const unsigned char *p, unsigned int len)
{
	const char *why = zrn_nci_check(p, len, proto);

	if (!!want_ok != !why) {
		printf("FAIL %-40s %s\n", name, why ? why : "allowed");
		fails++;
	} else {
		printf("ok   %-40s %s\n", name, why ? why : "allowed");
	}
}

#define T(ok, proto, name, ...) do { \
	static const unsigned char b[] = { __VA_ARGS__ }; \
	t(ok, proto, name, b, sizeof(b)); } while (0)

